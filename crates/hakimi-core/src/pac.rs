use std::collections::HashSet;
use std::net::SocketAddr;

use crate::config::AppConfig;

/// Generate the PAC script. Only enabled groups are intercepted; everything else is DIRECT.
/// A paused runtime (global switch off) returns a DIRECT-only script.
///
/// Exact domains are emitted as an object lookup instead of a long `||` chain. Browsers
/// call `FindProxyForURL` for every request, so a large custom list must not cost a
/// linear scan per navigation. Rules are initialized once at script load, not once per
/// call, and wildcard suffixes use the native `dnsDomainIs` instead of glob matching
/// with a freshly concatenated pattern on every iteration.
pub fn generate(config: &AppConfig, proxy: SocketAddr, paused: bool) -> String {
    let proxy_host = match proxy.ip() {
        std::net::IpAddr::V4(ip) => ip.to_string(),
        std::net::IpAddr::V6(ip) => format!("[{ip}]"),
    };
    let proxy = format!("PROXY {proxy_host}:{}; DIRECT", proxy.port());

    let mut exact = Vec::new();
    let mut wild = Vec::new();
    let mut seen_exact = HashSet::new();
    let mut seen_wild = HashSet::new();
    if !paused {
        for group in config.enabled_groups() {
            for rule in &group.domains {
                let domain = rule.pattern.as_str();
                if let Some(suffix) = domain.strip_prefix("*.") {
                    if seen_wild.insert(suffix) {
                        // Keep the leading dot: `dnsDomainIs(host, ".example.com")`
                        // matches subdomains but not the bare domain, which is the
                        // same contract as `*.example.com`.
                        wild.push(format!(".{suffix}"));
                    }
                } else if seen_exact.insert(domain) {
                    exact.push(domain);
                }
            }
        }
    }

    let mut script = String::with_capacity(256 + (exact.len() + wild.len()) * 40);
    script.push_str("// Generated by hakimi. Do not edit.\n");
    if !exact.is_empty() {
        script.push_str("var exact = {\n");
        for domain in &exact {
            script.push_str("  \"");
            script.push_str(&escape_js(domain));
            script.push_str("\": 1,\n");
        }
        script.push_str("};\n");
    }
    if !wild.is_empty() {
        script.push_str("var wild = [\n");
        for suffix in &wild {
            script.push_str("  \"");
            script.push_str(&escape_js(suffix));
            script.push_str("\",\n");
        }
        script.push_str("];\n");
    }
    script.push_str("function FindProxyForURL(url, host) {\n");
    script.push_str("  host = host.toLowerCase();\n");
    if exact.is_empty() && wild.is_empty() {
        script.push_str("  return \"DIRECT\";\n");
    } else {
        if !exact.is_empty() {
            script.push_str("  if (exact[host] === 1) {\n");
            script.push_str(&format!("    return \"{proxy}\";\n"));
            script.push_str("  }\n");
        }
        if !wild.is_empty() {
            script.push_str("  for (var i = 0; i < wild.length; i++) {\n");
            script.push_str("    if (dnsDomainIs(host, wild[i])) {\n");
            script.push_str(&format!("      return \"{proxy}\";\n"));
            script.push_str("    }\n");
            script.push_str("  }\n");
        }
        script.push_str("  return \"DIRECT\";\n");
    }
    script.push_str("}\n");
    script
}

fn escape_js(value: &str) -> String {
    value
        .replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('\n', "\\n")
        .replace('\r', "\\r")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn intercepts_only_enabled_groups() {
        let script = generate(
            &AppConfig::default(),
            "127.0.0.1:8443".parse().unwrap(),
            false,
        );
        assert!(script.contains("\"github.com\": 1"));
        assert!(script.contains("\".githubusercontent.com\""));
        assert!(script.contains("exact[host] === 1"));
        assert!(script.contains("dnsDomainIs(host, wild[i])"));
        assert!(!script.contains("shExpMatch"));
        assert!(script.contains("PROXY 127.0.0.1:8443; DIRECT"));
        // All groups ship enabled, so E-Hentai is intercepted as well.
        assert!(script.contains("e-hentai.org"));
        assert!(script.contains("return \"DIRECT\""));
        // The lookup tables must be initialized once, not rebuilt per call.
        let function = script.find("function FindProxyForURL").unwrap();
        assert!(script.find("var exact = {").unwrap() < function);
        assert!(script.find("var wild = [").unwrap() < function);
    }

    #[test]
    fn paused_returns_direct_only() {
        let script = generate(
            &AppConfig::default(),
            "127.0.0.1:8443".parse().unwrap(),
            true,
        );
        assert!(script.contains("return \"DIRECT\";"));
        assert!(!script.contains("PROXY 127.0.0.1:8443"));
        assert!(!script.contains("var exact"));
        assert!(!script.contains("var wild"));
    }

    #[test]
    fn ipv6_bind_is_bracketed() {
        let script = generate(&AppConfig::default(), "[::1]:8443".parse().unwrap(), false);
        assert!(script.contains("PROXY [::1]:8443; DIRECT"));
    }
}
